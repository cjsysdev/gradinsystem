/**
 * Front-end grade estimator — "what if I scored X?" sliders on the student
 * grade dashboard.
 *
 * READ THIS BEFORE EDITING.
 *
 * The project rule is that Grade_calculator is the only place a grade may be
 * computed. This file is the one sanctioned exception, and it stays sanctioned
 * only under these constraints:
 *
 *   1. It ports LAYER 2 (POLICY) ONLY — transmute / component / term_grade /
 *      final_grade. The data layer (rosters, sums, SQL) stays on the server.
 *   2. It hardcodes NO rule. The passing rate, io_type weights, scale anchors,
 *      term weights, the INC cutoff and the required-io_type list all arrive
 *      from PHP via Grade_calculator::policy(). A literal in here is a bug.
 *   3. Nothing it computes is authoritative. Nothing is posted, stored or fed
 *      back to the server. The real grade rendered by home.php is untouched and
 *      remains visible; the estimate is always labelled as an estimate.
 *   4. Parity with the PHP is enforced by a test, not by inspection:
 *      /grade_audit/jsparity runs these functions against vectors generated by
 *      Grade_calculator itself. Run it after ANY change to grading, on either
 *      side of the language boundary.
 *
 * The port is deliberately literal — same names, same argument order, same
 * guard clauses, same rounding points, same null semantics — so that a diff
 * against Grade_calculator.php reads as a translation rather than a rewrite.
 */
(function (window, document) {
    'use strict';

    // ==================================================================
    // POLICY — 1:1 port of Grade_calculator's pure functions
    // ==================================================================

    /**
     * PHP's round(), reproduced exactly.
     *
     * Naive scaling does not work. `Math.round(x * 100) / 100` disagrees with
     * PHP on every value that lands on a .xx5 boundary, and the parity harness
     * catches roughly 1.5% of random grades when it is used — enough to move a
     * real student's reported percentage by 0.01 and, at the cutoff, to flip an
     * INC.
     *
     * PHP (8.4+) rounds the SHORTEST DECIMAL REPRESENTATION that round-trips to
     * the double, not the double's raw binary value. So round(1.005, 2) is 1.01
     * even though 1.005 is stored as 1.00499999999999989, while
     * round(43.12 * 0.5 + 93.99 * 0.5, 2) is 68.55, because that sum's shortest
     * representation is 68.55499999999999 rather than 68.555.
     *
     * JavaScript's String(number) produces that same shortest round-tripping
     * decimal, so the two agree if the rounding is done on the digit string and
     * never on a scaled float. Ties go away from zero.
     *
     * If this ever starts failing in /grade_audit/jsparity, check the server's
     * PHP version first: round() changed its edge-case behaviour in 8.4, and
     * this mirrors the current one.
     */
    function phpRound(value, precision) {
        var num = parseFloat(value);
        if (!isFinite(num)) {
            return num;
        }
        var places = precision | 0;
        var negative = num < 0;
        var text = String(Math.abs(num));

        // Exponential notation, i.e. magnitudes no grade percentage can reach.
        // Nothing on that scale survives rounding to 2 or 4 places anyway.
        if (places < 0 || text.indexOf('e') !== -1) {
            var factor = Math.pow(10, places);
            var scaled = Math.round(Math.abs(num) * factor) / factor;
            return negative ? -scaled : scaled;
        }

        var dot = text.indexOf('.');
        var whole = (dot === -1) ? text : text.slice(0, dot);
        var frac = (dot === -1) ? '' : text.slice(dot + 1);

        if (frac.length <= places) {
            return num;
        }

        var digits = whole + frac.slice(0, places);
        if (frac.charCodeAt(places) - 48 >= 5) {
            digits = incrementDigits(digits);
        }

        var result = digitsToNumber(digits, places);
        return negative ? -result : result;
    }

    /** Add one to a non-negative integer digit string, carrying as needed. */
    function incrementDigits(digits) {
        var out = digits.split('');
        var i = out.length - 1;
        while (i >= 0) {
            if (out[i] === '9') {
                out[i] = '0';
                i--;
            } else {
                out[i] = String(Number(out[i]) + 1);
                break;
            }
        }
        if (i < 0) {
            out.unshift('1');
        }
        return out.join('');
    }

    /** Reinsert the decimal point rather than dividing, so nothing drifts. */
    function digitsToNumber(digits, places) {
        if (places === 0) {
            return Number(digits);
        }
        var padded = digits;
        while (padded.length <= places) {
            padded = '0' + padded;
        }
        var cut = padded.length - places;
        return Number(padded.slice(0, cut) + '.' + padded.slice(cut));
    }

    /** PHP is_numeric() for the value types that cross this boundary. */
    function isNumeric(value) {
        if (typeof value === 'number') {
            return isFinite(value);
        }
        if (typeof value === 'string') {
            if (value.trim() === '') {
                return false;
            }
            return !isNaN(Number(value)) && isFinite(Number(value));
        }
        return false;
    }

    /**
     * Port of Grade_calculator::transmute().
     *
     * Two straight lines meeting at passingRate: 0 -> floor, pr -> passing,
     * 100 -> ceiling. Returns a number, or null when the inputs cannot produce
     * a meaningful grade — never a string, and never a silent 0 for 'INC'.
     */
    function transmute(percentage, passingRate, policy) {
        if (percentage === null || percentage === undefined || percentage === '' || !isNumeric(percentage)) {
            return null;
        }
        if (passingRate === null || passingRate === undefined || !isNumeric(passingRate)) {
            return null;
        }

        var pct = parseFloat(percentage);
        var pr = parseFloat(passingRate);

        // A passing rate of 0 or 100 makes one of the two segments a division
        // by zero.
        if (pr <= 0 || pr >= 100) {
            return null;
        }
        if (pct < 0 || pct > 100) {
            return null;
        }

        var floor = parseFloat(policy.point_floor);
        var passing = parseFloat(policy.point_passing);
        var ceiling = parseFloat(policy.point_ceiling);

        var gp;
        if (pct <= pr) {
            gp = floor - ((floor - passing) / pr) * pct;
        } else {
            gp = passing - ((passing - ceiling) / (100 - pr)) * (pct - pr);
        }

        return phpRound(gp, 2);
    }

    /**
     * Port of Grade_calculator::component().
     *
     * Note that grade_point and weighted_grade are derived from the UNROUNDED
     * percentage, while the reported percentage is rounded to 2 — exactly as
     * the PHP does. Rounding first would drift.
     */
    function component(sumScore, sumMax, passingRate, weight, policy) {
        var score = parseFloat(sumScore) || 0;
        var max = parseFloat(sumMax) || 0;

        var percentage = (max > 0) ? (score / max) * 100 : null;

        return {
            total_score: phpRound(score, 2),
            total_max_score: phpRound(max, 2),
            percentage: (percentage === null) ? null : phpRound(percentage, 2),
            grade_point: transmute(percentage, passingRate, policy),
            weighted_grade: (percentage === null) ? null : phpRound(percentage * (parseFloat(weight) / 100), 4)
        };
    }

    /**
     * The estimator's entry point into component(): the slider hands over a
     * percentage directly rather than a score/max pair.
     *
     * Kept as its own function, expressed with the same three expressions
     * component() uses, so the two cannot drift. Passing (pct, 100) through
     * component() would be equivalent but would quietly misreport
     * total_max_score, which the readout needs.
     */
    function componentFromPercentage(percentage, passingRate, weight, policy) {
        if (percentage === null || percentage === undefined || !isNumeric(percentage)) {
            return {
                percentage: null,
                grade_point: null,
                weighted_grade: null
            };
        }
        var pct = parseFloat(percentage);
        return {
            percentage: phpRound(pct, 2),
            grade_point: transmute(pct, passingRate, policy),
            weighted_grade: phpRound(pct * (parseFloat(weight) / 100), 4)
        };
    }

    /**
     * Port of Grade_calculator::term_grade().
     *
     * A term is INC unless every required io_type has at least one assessment.
     * Weights are never renormalised — a term missing its Major Exam does not
     * scale the rest up. `components` is an array; each entry carries its own
     * iotype_id.
     */
    function termGrade(components, requiredIotypes, passingRate, policy) {
        var present = [];
        var pending = 0;
        var i;

        for (i = 0; i < components.length; i++) {
            // PHP's !empty(): 0, null and undefined all mean "not present".
            if (components[i].n_assessments) {
                present.push(parseInt(components[i].iotype_id, 10));
            }
            pending += parseInt(components[i].n_ungraded, 10) || 0;
        }

        var missing = [];
        for (i = 0; i < requiredIotypes.length; i++) {
            var id = parseInt(requiredIotypes[i], 10);
            if (present.indexOf(id) === -1) {
                missing.push(id);
            }
        }

        if (missing.length > 0) {
            return {
                status: 'inc',
                reason: 'missing_components',
                percentage: null,
                grade_point: null,
                missing_iotypes: missing,
                pending_count: pending
            };
        }

        var percentage = 0.0;
        for (i = 0; i < components.length; i++) {
            percentage += parseFloat(components[i].weighted_grade) || 0;
        }
        percentage = phpRound(percentage, 2);

        return {
            status: 'ok',
            reason: null,
            percentage: percentage,
            grade_point: transmute(percentage, passingRate, policy),
            missing_iotypes: [],
            pending_count: pending
        };
    }

    /**
     * Port of Grade_calculator::final_grade().
     *
     * INC in either term propagates. A grade point above fail_as_inc_above is
     * reported as INC — but the percentage and grade point are still returned,
     * and the estimator shows them: "INC" alone tells a student nothing about
     * which way to move the slider.
     */
    function finalGrade(midterm, final, passingRate, policy) {
        if ((midterm && midterm.status) !== 'ok' || (final && final.status) !== 'ok') {
            return {
                status: 'inc',
                reason: 'term_incomplete',
                percentage: null,
                grade_point: null
            };
        }

        var weights = policy.term_weights;
        var percentage = phpRound(
            (midterm.percentage * parseFloat(weights.midterm)) + (final.percentage * parseFloat(weights.final)),
            2
        );
        var gradePoint = transmute(percentage, passingRate, policy);

        var failAbove = policy.fail_as_inc_above;
        if (failAbove !== null && failAbove !== undefined && gradePoint !== null && gradePoint > parseFloat(failAbove)) {
            return {
                status: 'inc',
                reason: 'below_passing',
                percentage: percentage,
                grade_point: gradePoint
            };
        }

        return {
            status: 'ok',
            reason: null,
            percentage: percentage,
            grade_point: gradePoint
        };
    }

    // Exported so /grade_audit/jsparity can run these against PHP-generated
    // vectors. The UI below is the only other consumer.
    var GradePolicy = {
        phpRound: phpRound,
        isNumeric: isNumeric,
        transmute: transmute,
        component: component,
        componentFromPercentage: componentFromPercentage,
        termGrade: termGrade,
        finalGrade: finalGrade,
        // Composition step, exported for the same reason: the parity harness
        // asserts that an untouched estimate equals the server's own grade.
        initialState: function (data) { return initialState(data); },
        estimateAll: function (data, current) { return estimateAll(data, current); }
    };
    window.GradePolicy = GradePolicy;

    // ==================================================================
    // UI — reads state, calls POLICY, writes the DOM. No arithmetic of its own.
    // ==================================================================

    var TERMS = ['midterm', 'final'];
    var TERM_LABELS = { midterm: 'Midterm', final: 'Final Term' };

    var payload = null;
    var state = null;      // term -> iotype_id -> { included: bool, pct: number }
    var active = false;

    function fmt(value, decimals) {
        if (value === null || value === undefined) {
            return '—';
        }
        return phpRound(value, decimals).toFixed(decimals);
    }

    function el(tag, className, text) {
        var node = document.createElement(tag);
        if (className) { node.className = className; }
        if (text !== undefined && text !== null) { node.textContent = text; }
        return node;
    }

    function componentsFor(term) {
        return payload[term] || [];
    }

    function iotypeName(term, iotypeId) {
        var list = componentsFor(term);
        for (var i = 0; i < list.length; i++) {
            if (parseInt(list[i].iotype_id, 10) === parseInt(iotypeId, 10)) {
                return list[i].iotype_name;
            }
        }
        // Fall back to the other term: required_iotypes is global, so a
        // component can be required without appearing in this term's list.
        var other = (term === 'midterm') ? 'final' : 'midterm';
        var otherList = componentsFor(other);
        for (var j = 0; j < otherList.length; j++) {
            if (parseInt(otherList[j].iotype_id, 10) === parseInt(iotypeId, 10)) {
                return otherList[j].iotype_name;
            }
        }
        return 'io_type ' + iotypeId;
    }

    /**
     * Initial slider state: reality, with nothing invented.
     *
     * The starting percentage is recomputed from the raw sums rather than taken
     * from the payload's `percentage` field. That field is rounded to 2 places,
     * but Grade_calculator::component() derives weighted_grade from the
     * UNROUNDED percentage — seeding from the rounded one would make the
     * estimator open showing a term total a hundredth away from the grade
     * printed directly above it. Recomputing here walks the same path the PHP
     * did, so an untouched estimate reproduces the server exactly.
     *
     * Pure and exported: /grade_audit/jsparity asserts that property against
     * PHP-computed expectations.
     */
    function initialState(data) {
        var next = {};
        TERMS.forEach(function (term) {
            next[term] = {};
            (data[term] || []).forEach(function (c) {
                var recorded = c.n_assessments > 0 && c.percentage !== null;
                var max = parseFloat(c.total_max_score);
                var exact;
                if (!recorded) {
                    exact = 0;
                } else if (max > 0) {
                    exact = (parseFloat(c.total_score) / max) * 100;
                } else {
                    exact = parseFloat(c.percentage);
                }
                next[term][c.iotype_id] = { included: recorded, pct: exact };
            });
        });
        return next;
    }

    /** Run the POLICY layer over the current slider state for one term. */
    function estimateTerm(data, current, term) {
        var built = (data[term] || []).map(function (c) {
            var s = current[term][c.iotype_id];
            if (!s.included) {
                return {
                    iotype_id: c.iotype_id,
                    n_assessments: 0,
                    n_ungraded: c.n_ungraded,
                    percentage: null,
                    grade_point: null,
                    weighted_grade: null
                };
            }
            var computed = componentFromPercentage(s.pct, data.passing_rate, c.iotype_percentage, data.policy);
            return {
                iotype_id: c.iotype_id,
                // Any non-zero value satisfies term_grade()'s presence check;
                // the real count is kept where there is one so the estimate
                // reports the same shape as the server.
                n_assessments: c.n_assessments > 0 ? c.n_assessments : 1,
                // Carried through rather than zeroed: term_grade() reports it,
                // and a needless divergence here would be a parity failure the
                // estimator could not justify. It simply is not displayed.
                n_ungraded: c.n_ungraded,
                percentage: computed.percentage,
                grade_point: computed.grade_point,
                weighted_grade: computed.weighted_grade
            };
        });

        return {
            components: built,
            grade: termGrade(built, data.required_iotypes, data.passing_rate, data.policy)
        };
    }

    /** Both terms plus the overall blend, for one slider state. */
    function estimateAll(data, current) {
        var midtermResult = estimateTerm(data, current, 'midterm');
        var finalResult = estimateTerm(data, current, 'final');
        return {
            midterm: midtermResult,
            final: finalResult,
            overall: finalGrade(midtermResult.grade, finalResult.grade, data.passing_rate, data.policy)
        };
    }

    function renderComponentRow(term, config, mount) {
        var s = state[term][config.iotype_id];
        mount.innerHTML = '';

        var head = el('div', 'gc-est-head');
        head.appendChild(el('strong', null, config.iotype_name));
        head.appendChild(el('span', 'gc-est-weight', ' (' + config.iotype_percentage + '%)'));
        mount.appendChild(head);

        var hypothetical = config.n_assessments === 0;

        if (hypothetical) {
            var wrap = el('label', 'gc-est-include');
            var box = document.createElement('input');
            box.type = 'checkbox';
            box.checked = s.included;
            box.addEventListener('change', function () {
                state[term][config.iotype_id].included = box.checked;
                render();
            });
            wrap.appendChild(box);
            wrap.appendChild(el('span', null, ' Nothing recorded yet — assume a score'));
            mount.appendChild(wrap);
        }

        var slider = document.createElement('input');
        slider.type = 'range';
        slider.className = 'gc-est-slider custom-range';
        slider.min = '0';
        slider.max = '100';
        // 0.01 so the slider can open at the student's exact real percentage —
        // the estimate must start identical to the grade shown above it.
        slider.step = '0.01';
        slider.value = String(s.pct);
        slider.disabled = !s.included;
        slider.setAttribute('aria-label', 'Estimated ' + config.iotype_name + ' percentage for ' + TERM_LABELS[term]);

        slider.addEventListener('input', function () {
            state[term][config.iotype_id].pct = parseFloat(slider.value);
            render();
        });
        // Arrow keys at step 0.01 would be unusable; make them whole points and
        // keep the fine step on Shift.
        slider.addEventListener('keydown', function (event) {
            var keys = { ArrowLeft: -1, ArrowDown: -1, ArrowRight: 1, ArrowUp: 1 };
            if (!(event.key in keys) || event.shiftKey || slider.disabled) {
                return;
            }
            event.preventDefault();
            var next = Math.min(100, Math.max(0, phpRound(parseFloat(slider.value) + keys[event.key], 2)));
            slider.value = String(next);
            state[term][config.iotype_id].pct = next;
            render();
        });
        mount.appendChild(slider);

        var readout = el('div', 'gc-est-readout');
        if (!s.included) {
            readout.appendChild(el('span', 'text-muted', 'Excluded — this term stays INC until it is recorded.'));
        } else {
            var computed = componentFromPercentage(s.pct, payload.passing_rate, config.iotype_percentage, payload.policy);
            readout.appendChild(el('strong', null, fmt(computed.percentage, 1) + '%'));
            readout.appendChild(el('span', null, '  (' + (computed.grade_point === null ? 'N/A' : fmt(computed.grade_point, 2)) + ')'));

            var detail = el('div', 'gc-est-detail');
            if (config.total_max_score > 0) {
                var points = (s.pct / 100) * parseFloat(config.total_max_score);
                detail.appendChild(el('span', null,
                    '≈ ' + fmt(points, 1) + ' / ' + fmt(config.total_max_score, 0) + ' pts'));
                detail.appendChild(el('span', 'gc-est-sep', ' · '));
            }
            detail.appendChild(el('span', null,
                'contributes ' + fmt(computed.weighted_grade, 2) + ' of ' + config.iotype_percentage));
            if (hypothetical) {
                detail.appendChild(el('span', 'gc-est-sep', ' · '));
                detail.appendChild(el('span', 'gc-est-flag', 'hypothetical'));
            }
            readout.appendChild(detail);
        }
        mount.appendChild(readout);
    }

    function renderTermTotal(term, result, mount) {
        mount.innerHTML = '';
        mount.appendChild(el('div', null, 'Estimated Total ' + TERM_LABELS[term] + ' Grade:'));

        var grade = result.grade;
        if (grade.status !== 'ok') {
            mount.appendChild(el('div', 'gc-est-inc', 'INC'));
            var names = grade.missing_iotypes.map(function (id) { return iotypeName(term, id); });
            mount.appendChild(el('small', null,
                names.length
                    ? 'Still missing: ' + names.join(', ') + '. Tick a component above to see a "what if" total.'
                    : 'Incomplete.'));
            return;
        }

        var bar = el('div', 'progress m-2');
        var fill = el('div', 'progress-bar gc-est-bar');
        fill.setAttribute('role', 'progressbar');
        fill.style.width = grade.percentage + '%';
        fill.setAttribute('aria-valuenow', String(grade.percentage));
        fill.setAttribute('aria-valuemin', '0');
        fill.setAttribute('aria-valuemax', '100');
        bar.appendChild(fill);
        mount.appendChild(bar);

        mount.appendChild(el('div', null, fmt(grade.percentage, 2) + '% ( ' + fmt(grade.grade_point, 2) + ' )'));
    }

    function renderOverall(overall, mount) {
        mount.innerHTML = '';
        mount.appendChild(el('div', null, 'Estimated Overall Final Grade:'));

        if (overall.status === 'ok') {
            mount.appendChild(el('strong', 'gc-est-overall', fmt(overall.grade_point, 2)));
            mount.appendChild(el('span', null, ' (' + fmt(overall.percentage, 2) + '%)'));
            return;
        }

        if (overall.reason === 'below_passing') {
            // The number is shown deliberately: the cutoff turns it into INC on
            // the record, but a student adjusting sliders needs to see how far
            // off it is.
            mount.appendChild(el('strong', 'gc-est-overall gc-est-failing', fmt(overall.grade_point, 2)));
            mount.appendChild(el('span', null, ' (' + fmt(overall.percentage, 2) + '%)'));
            mount.appendChild(el('div', 'gc-est-inc-note',
                'Below passing — this would be recorded as INC.'));
            return;
        }

        mount.appendChild(el('div', 'gc-est-inc', 'INC'));
        mount.appendChild(el('small', null, 'Both terms must be complete before an overall grade exists.'));
    }

    function render() {
        var results = estimateAll(payload, state);

        TERMS.forEach(function (term) {
            componentsFor(term).forEach(function (config) {
                var block = document.querySelector(
                    '.gc-component[data-gc-term="' + term + '"][data-gc-iotype="' + config.iotype_id + '"] .gc-estimate'
                );
                if (block) {
                    renderComponentRow(term, config, block);
                }
            });

            var totalMount = document.querySelector('.gc-term-total[data-gc-term="' + term + '"] .gc-estimate');
            if (totalMount) {
                renderTermTotal(term, results[term], totalMount);
            }
        });

        var overallMount = document.querySelector('.gc-overall .gc-estimate');
        if (overallMount) {
            renderOverall(results.overall, overallMount);
        }
    }

    function setActive(next) {
        active = next;
        document.querySelectorAll('.gc-actual').forEach(function (node) {
            node.hidden = active;
        });
        document.querySelectorAll('.gc-estimate').forEach(function (node) {
            node.hidden = !active;
        });

        var banner = document.getElementById('gc-estimate-banner');
        if (banner) { banner.hidden = !active; }

        var toggle = document.getElementById('gc-estimate-toggle');
        if (toggle) {
            toggle.textContent = active ? 'Show my actual grades' : 'Estimate my grade';
            toggle.setAttribute('aria-pressed', active ? 'true' : 'false');
            toggle.classList.toggle('btn-secondary', active);
            toggle.classList.toggle('btn-outline-primary', !active);
        }

        var reset = document.getElementById('gc-estimate-reset');
        if (reset) { reset.hidden = !active; }

        if (active) { render(); }
    }

    function init() {
        var payloadEl = document.getElementById('gc-estimator-payload');
        var toggle = document.getElementById('gc-estimate-toggle');
        if (!payloadEl || !toggle) {
            return;
        }

        try {
            payload = JSON.parse(payloadEl.textContent);
        } catch (e) {
            // A broken payload must not take the real grades down with it.
            toggle.hidden = true;
            return;
        }
        if (!payload || !payload.policy) {
            toggle.hidden = true;
            return;
        }
        payload.required_iotypes = (payload.required_iotypes || []).map(function (id) {
            return parseInt(id, 10);
        });

        state = initialState(payload);

        toggle.addEventListener('click', function () { setActive(!active); });

        var reset = document.getElementById('gc-estimate-reset');
        if (reset) {
            reset.addEventListener('click', function () {
                state = initialState(payload);
                render();
            });
        }
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
})(window, document);
